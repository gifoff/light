pub mod fields;
/// Рендер и парсинг HTML-шаблонов, кэш, фабрики элементов.
#[allow(clippy::module_inception)]
pub mod parse;
/// Парсинг стилей, вспомогательные парсеры, конфигурация окна.
pub mod style;
