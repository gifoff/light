//! Реактивное ядро Relay: свойства, обозреватели, эффекты и подписки.
//!
//! Модель повторяет реактивность Vue 3:
//! * [`Property`] — ячейка значения (аналог `ref`);
//! * [`Proxy`] — маркер «реактивного класса» (аналог `reactive`);
//! * обозреватель ([`with_observer`]) — центральный реестр, который запоминает,
//!   какие эффекты (подписчики [`watch`]) читали какие свойства, и уведомляет
//!   их при записи, а также запрашивает перерисовку окна;
//! * [`Watcher`] — подписка на изменения с пользовательским обработчиком.
//!
//! Чтения реактивных свойств внутри `render` компонента фиксируются
//! автоматически: любое изменение свойства запрашивает перерисовку окна,
//! а сравнение деревьев ([`crate::vdom::diff`]) гарантирует, что будут
//! обновлены только реально изменившиеся элементы.

mod observer;
mod property;
mod proxy;
mod watch;

pub use observer::{EffectId, Observer, PropertyId, set_repaint_requester, with_observer};
pub use property::Property;
pub use proxy::{Proxy, ProxyState};
pub use watch::{Watcher, watch};
