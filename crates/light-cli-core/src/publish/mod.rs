//! Команда `light publish`: оркестрация публикации крейтов воркспейса.
//!
//! Граф строится из `cargo metadata --no-deps`: модуль не парсит `Cargo.toml`
//! руками для топологии. Внешние эффекты (запуск `cargo`/`git`, сеть, ожидание)
//! спрятаны за трейтами [`CommandRunner`], [`RegistryProbe`] и [`Sleeper`],
//! поэтому логика графа, ретраев и проверки версий тестируется без процессов и
//! без сети.

/// Парсинг метаданных воркспейса, построение плана публикации, валидация.
pub mod base;
/// Гейты pre-flight, упаковка, вызов `cargo publish`.
pub mod gates;
/// Классификация сбоев, ретраи, проверка реестра.
pub mod retry;
#[cfg(test)]
mod tests;

pub use base::*;
pub use gates::*;
pub use retry::*;
